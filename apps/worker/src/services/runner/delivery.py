"""Hand the verified work over according to the task's git flow.

- ``branch``    — push the task branch and open a pull request
- ``commit``    — rebase onto and push straight to the default branch
- ``patch``     — keep the commits local (patch files are exported later)
- ``untracked`` — leave the edits uncommitted in the operator's folder
"""

from __future__ import annotations

import logging
from dataclasses import dataclass
from decimal import Decimal

from services import git_ops

from .context import TaskContext

logger = logging.getLogger(__name__)


@dataclass(frozen=True)
class Handover:
    pr_url: str | None
    #: False only when a direct commit to the default branch failed.
    commit_ok: bool


@dataclass(frozen=True)
class AttemptMetrics:
    attempt: int
    turns: int
    cost_usd: Decimal
    duration_ms: int


def pr_body(ctx: TaskContext, *, summary: str, metrics: AttemptMetrics) -> str:
    verify_note = "Skipped" if ctx.task.skip_verify else "PASSED"
    lint_line = f"- Lint: {verify_note}\n" if ctx.repo.lint_cmd else ""
    failover_line = f"- Failover: {ctx.failover_label}\n" if ctx.failover_label else ""
    footer = "*Generated by DevServer autonomous agent"
    footer += f" (failover: {ctx.failover_label})*" if ctx.failover_label else "*"
    return (
        f"## {ctx.task.key}: {ctx.task.title}\n\n"
        f"### Changes\n{summary[:2000]}\n\n"
        f"### Verification\n"
        f"- Build: {verify_note}\n- Tests: {verify_note}\n{lint_line}\n"
        f"### Metrics\n"
        f"{failover_line}"
        f"- Attempts: {metrics.attempt}/{ctx.repo.max_retries}\n"
        f"- Claude turns: {metrics.turns}\n"
        f"- Cost: ${metrics.cost_usd}\n"
        f"- Duration: {metrics.duration_ms // 1000}s\n\n"
        f"---\n{footer}"
    )


async def hand_over(ctx: TaskContext, *, summary: str, metrics: AttemptMetrics) -> Handover:
    repo, task = ctx.repo, ctx.task
    if ctx.git_flow == "branch":
        pr_url = await git_ops.create_gitea_pr(
            worktree_path=ctx.worktree_path,
            branch_name=ctx.branch_name,
            default_branch=repo.default_branch,
            title=f"[{task.key}] {task.title}",
            body=pr_body(ctx, summary=summary, metrics=metrics),
            gitea_url=repo.gitea_url,
            gitea_owner=repo.gitea_owner,
            gitea_repo=repo.gitea_repo,
            gitea_token=repo.gitea_token,
            provider=repo.provider,
            clone_url=repo.clone_url,
        )
        if not pr_url:
            logger.warning("PR creation failed for %s, branch was pushed", task.key)
        return Handover(pr_url=pr_url, commit_ok=True)

    if ctx.git_flow == "commit":
        commit_ok = await git_ops.commit_to_default_branch(
            worktree_path=ctx.worktree_path,
            branch_name=ctx.branch_name,
            default_branch=repo.default_branch,
            task_key=task.key,
            title=task.title,
        )
        if not commit_ok:
            logger.warning("Direct commit failed for %s", task.key)
        return Handover(pr_url=None, commit_ok=commit_ok)

    logger.info("git_flow=%s: nothing to push for %s", ctx.git_flow, task.key)
    return Handover(pr_url=None, commit_ok=True)
